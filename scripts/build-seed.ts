// Generates migrations/seed.sql from scripts/seed-content.ts, rendering Markdown
// with the same code the CMS uses on save. Run: bun run db:build-seed
import { renderBody } from '../src/lib/body'
import { existsSync } from 'node:fs'
import { articles, authors } from './seed-content'

// Share cards rendered by scripts/share-cards.ts, if present.
const shareCard = (slug: string) =>
  existsSync(new URL(`../public/placeholder/share/${slug}.webp`, import.meta.url)) ? `/placeholder/share/${slug}.webp` : ''

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const ago = (hours: number) => `unixepoch() - ${Math.round(hours * 3600)}`

const lines = [
  '-- Local development seed. Generated by scripts/build-seed.ts; do not edit by hand.',
  '-- Timestamps are relative to when the seed runs, so the front page always looks fresh.',
  // Re-seeding replaces only the seeded stories; anything written in the local CMS is kept.
  `DELETE FROM articles WHERE slug IN (${articles.map((a) => q(a.slug)).join(', ')});`,
  ...authors.map(
    (au) => `INSERT INTO authors (email, name, slug, bio, title, role) VALUES (${q(au.email)}, ${q(au.name)}, ${q(au.slug)}, ${q(au.bio)}, ${q(au.title)}, 'editor')
  ON CONFLICT(email) DO UPDATE SET name = excluded.name, slug = excluded.slug, bio = excluded.bio, title = excluded.title;`,
  ),
  '',
]
const emailOf = (slug: string) => {
  const au = authors.find((x) => x.slug === slug)
  if (!au) throw new Error(`Unknown author slug: ${slug}`)
  return au.email
}

for (const a of articles) {
  const pub = ago(a.hoursAgo)
  const upd = ago(a.updatedHoursAgo ?? a.hoursAgo)
  const format = a.format ?? 'story'
  const r = renderBody(format, a.body)
  const credit = a.image ? (a.credit ?? 'Illustration by Bloatberg') : ''
  lines.push(
    `INSERT INTO articles (slug, title, dek, section, body_md, body_html, read_minutes, image_key, image_alt, image_credit, label, dateline, featured, format, live_latest, live_count, review_score, share_key, status, author_id, published_at, created_at, updated_at)
VALUES (${q(a.slug)}, ${q(a.title)}, ${q(a.dek)}, ${q(a.section)}, ${q(a.body)}, ${q(r.body_html)}, ${r.read_minutes}, ${q(a.image)}, ${q(a.alt)}, ${q(credit)}, ${q(a.label ?? '')}, ${q(a.dateline ?? '')}, ${a.featured ? 1 : 0}, ${q(format)}, ${q(r.live_latest)}, ${r.live_count}, ${r.review_score ?? 'NULL'}, ${q(shareCard(a.slug))}, 'published', (SELECT id FROM authors WHERE email = ${q(emailOf(a.author))}), ${pub}, ${pub}, ${upd});`,
    '',
  )
}

// ---------- Sample page views (local dev only) ----------
// Gives the CMS stats pages something to show before real traffic exists. Deterministic, and
// day keys are computed when the seed runs (approximately Eastern time). Clear with db:clear-views:local.
let seed = 42
const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647)
const SOURCES: [string, number][] = [
  ['Direct', 0.24], ['Front page', 0.2], ['news.ycombinator.com', 0.16], ['x.com', 0.1], ['Google', 0.08],
  ['reddit.com', 0.07], ['Other articles', 0.06], ['linkedin.com', 0.04], ['bsky.app', 0.03], ['Section pages', 0.02],
]
const dayExpr = (back: number) => `date(unixepoch() - 4 * 3600 - ${back} * 86400, 'unixepoch')`
lines.push('-- Sample page views for local development. Not real traffic.')
for (const a of articles) {
  const id = `(SELECT id FROM articles WHERE slug = ${q(a.slug)})`
  const base = (a.format === 'brief' ? 140 : a.featured ? 2400 : 900) * (0.6 + rand() * 0.8)
  const ageDays = Math.floor(a.hoursAgo / 24)
  for (let back = ageDays; back >= 0; back--) {
    const age = ageDays - back
    // Today is a partial day; everything decays after launch day.
    const views = Math.max(1, Math.round(base * Math.pow(0.42, age) * (0.75 + rand() * 0.5) * (back === 0 ? 0.55 : 1)))
    lines.push(`INSERT INTO article_views (article_id, day, views) VALUES (${id}, ${dayExpr(back)}, ${views});`)
    let left = views
    for (const [src, w] of SOURCES) {
      const n = src === 'Section pages' ? left : Math.min(left, Math.round(views * w * (0.6 + rand() * 0.8)))
      if (n <= 0) continue
      left -= n
      lines.push(`INSERT INTO article_sources (article_id, day, source, views) VALUES (${id}, ${dayExpr(back)}, ${q(src)}, ${n});`)
    }
  }
}
lines.push('')

await Bun.write(new URL('../migrations/seed.sql', import.meta.url), lines.join('\n'))
console.log(`Wrote migrations/seed.sql (${articles.length} articles)`)
